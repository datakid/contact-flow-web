(() => {
  const S = window.CFSearch, F = window.CFFormats;
  const out = document.getElementById('out');
  let pass = 0, fail = 0;
  const ok = (cond, label) => {
    const li = document.createElement('li');
    li.className = cond ? 'p' : 'f';
    li.textContent = (cond ? 'PASS ' : 'FAIL ') + label;
    out.append(li);
    cond ? pass++ : fail++;
    console.log((cond ? 'PASS ' : 'FAIL ') + label);
  };
  const contacts = window.CFSample.map(([name, phones, company, emails, aliases]) => ({ id: name, name, phones, company, emails, aliases }));
  const idx = S.buildIndex(contacts);
  const names = q => (S.search(q, idx) || []).map(r => r.e.c.name);
  const has = (q, n) => { const r = names(q); ok(r.includes(n), `search "${q}" → ${n}  [${r.slice(0, 5).join(', ')}]`); };
  has('jonatan', 'Jonathan Smith');
  has('jose', 'José Álvarez');
  has('احمد', 'أحمد الخطيب');
  has('wang', '王伟');
  has('lxl', '李小龙');
  has('mohamed', 'محمد عبد الله');
  has('mohamed', 'Mohammed Ali');
  has('ahmed', 'أحمد الخطيب');
  has('abu omar', 'خالد العتيبي');
  has('أبو عمر', 'خالد العتيبي');
  has('٠٥٠ ١٢٣', 'محمد عبد الله');
  has('5550101', 'Jonathan Smith');
  has('pepe', 'José Álvarez');
  has('hart studio', 'Amelia Hart');
  ok(!names('xyzzy').length, 'no results for xyzzy');
  ok(names('am')[0] === 'Amelia Hart', 'prefix ranks first: ' + names('am')[0]);

  const csv = 'Name,Phone,Email,Nickname\n"Smith, John",+1 415 555 0101;+1 415 555 0102,j@x.com,Johnny\nمحمد,050 123 4567,,أبو أحمد';
  const r1 = F.parseText(csv);
  ok(r1.kind === 'csv' && r1.contacts.length === 2, 'csv parse 2');
  ok(r1.contacts[0].name === 'Smith, John' && r1.contacts[0].phones.length === 2 && r1.contacts[0].aliases[0] === 'Johnny', 'csv fields');
  const vcf = 'BEGIN:VCARD\r\nVERSION:2.1\r\nN;CHARSET=UTF-8;ENCODING=QUOTED-PRINTABLE:=D8=B9=D9=84=D9=8A;;;;\r\nTEL;CELL:+966 50 000 0000\r\nNICKNAME:Ali,Abu Hasan\r\nEND:VCARD\r\nBEGIN:VCARD\r\nVERSION:3.0\r\nFN:Ava Thompson\r\nTEL;TYPE=CELL:+1 646 555 0142\r\nORG:Acme;Sales\r\nEND:VCARD';
  const r2 = F.parseText(vcf);
  ok(r2.kind === 'vcard' && r2.contacts.length === 2, 'vcard parse 2');
  ok(r2.contacts[0].name === 'علي' && r2.contacts[0].aliases.length === 2, 'vcard QP + nickname: ' + r2.contacts[0].name);
  ok(r2.contacts[1].company === 'Acme · Sales', 'vcard org');
  const r3 = F.parseText('John 0501234567\nJane: +44 7700 900461, jane@x.com');
  ok(r3.kind === 'txt' && r3.contacts.length === 2 && r3.contacts[1].name === 'Jane' && r3.contacts[1].emails.length === 1, 'txt parse');
  const r4 = F.parseText('[{"name":"A","phones":["1234567"],"aliases":["x"]}]');
  ok(r4.kind === 'json' && r4.contacts[0].aliases[0] === 'x', 'json parse');
  const o = { format: 'vcard', numberStyle: 'intl', everyNumber: true, header: true, emails: true, company: true, notes: true, aliases: true, contactId: true };
  const ex = F.exportData([{ id: 'abc', name: 'Smith, John', phones: ['+1 (415) 555-0101'], emails: [], aliases: ['Jo,hnny'], company: '', note: '' }], o);
  const back = F.parseVCard(ex.data);
  ok(back[0].name === 'Smith, John' && back[0].phones[0] === '+14155550101' && back[0].aliases[0] === 'Jo,hnny' && back[0].contact_id === 'abc', 'vcard round trip');
  const exc = F.exportData([{ id: 'abc', name: 'A "B"', phones: ['1', '2'], emails: [], aliases: [], company: 'C', note: '' }], Object.assign({}, o, { format: 'csv' }));
  const backc = F.rowsToContacts(F.parseCSV(exc.data));
  ok(backc[0].name === 'A "B"' && backc[0].contact_id === 'abc', 'csv round trip');
  const xl = F.exportData(contacts.slice(0, 3).map(c => Object.assign({ note: '' }, c)), Object.assign({}, o, { format: 'excel' }));
  const wb = XLSX.read(xl.data, { type: 'array' });
  const rows = XLSX.utils.sheet_to_json(wb.Sheets[wb.SheetNames[0]], { header: 1, raw: false });
  const backx = F.rowsToContacts(rows);
  ok(backx.length === 3 && backx[0].name === contacts[0].name, 'xlsx round trip');
  const big = Array.from({ length: 150000 }, (_, i) => ({ id: 'i' + i, name: 'N' + i, phones: ['+1555' + i], emails: [], aliases: [], company: '', note: '' }));
  const bigCsv = F.exportData(big, o).data;
  ok(F.exportData(big, Object.assign({}, o, { format: 'csv' })).data.length > 150000, 'csv export of 150k rows');
  ok(F.rowsToContacts(F.parseCSV('Name,Phone\n' + big.map(c => c.name + ',' + c.phones[0]).join('\n'))).length === 150000, 'csv import of 150k rows');
  const h = document.createElement('h2');
  h.id = 'summary';
  h.textContent = `${pass} passed, ${fail} failed`;
  document.body.prepend(h);
  console.log(h.textContent);
})();
