export type WizardStrings = typeof en;

export function wizardStrings(lang: Language): WizardStrings {
  return lang === "ar" ? ar : en;
}

export function useW(): WizardStrings {
  const lang = useApp((s) => s.lang);
  return wizardStrings(lang);
}
